// Детальніше про reduce у цьому коді:

// reduce отримує: функцію-правило shiftAdd та початкове значення накопичувача 0
// Далі reduce виконує свій алгоритм:
// Створює власну внутрішню змінну-накопичувач і записує туди 0
// 1) Проходить по масиву octets зліва направо
// 2) На кожному елементі:
//    а) бере поточний елемент масиву;
//    б) викликає shiftAdd(накопичувач, поточний_елемент);
//    в) результат виклику записує назад у накопичувач.
//    г) після обробки останнього елемента reduce повертає підсумкове значення свого накопичувача
//      (тобто фінальне число, яке вийшло в результаті проходу по всьому масиву)




//Покрокове виконання для '10.0.0.1':

// Масив: octets = ['10', '0', '0', '1']. Початковий накопичувач: 0.

// Ітерація 1 (індекс 0):
// 1) reduce викликає shiftAdd(0, '10')
// 2) у shiftAdd: acc = 0, octet = '10'
// 3) тіло функції shiftAdd: (0 << 8) + parseInt('10', 10) = 0 + 10 = 10
// 4) reduce записує в накопичувач 10

// Ітерація 2 (індекс 1):
// 1) reduce викликає shiftAdd(10, '0');
// 2) у shiftAdd: acc = 10, octet = '0';
// 3) тіло функції shiftAdd: (10 << 8) + parseInt('0', 10) = 2560 + 0 = 2560;
// 4) reduce записує в накопичувач 2560.

// Ітерація 3 (індекс 2):
// 1) reduce викликає shiftAdd(2560, '0');
// 2) у shiftAdd: acc = 2560, octet = '0';
// 3) тіло функції shiftAdd: (2560 << 8) + parseInt('0', 10) = 655360 + 0 = 655360;
// 4) reduce записує в накопичувач 655360.

// Ітерація 4 (індекс 3):
