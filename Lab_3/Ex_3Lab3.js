'use strict';

function ipToInt(ip = '127.0.0.1') {     // Створення функції, у якої аргумент ip за замовчуванням = '127.0.0.1'
  const octets = ip.split('.');     // Розбиваємо рядок ip на масив октетів ['октет1', 'октет2', 'октет3', 'октет4']
  function shiftAdd(acc, octet) {   // Функція-правило для reduce: acc — те, що вже накопичили на попередніх кроках, octet — поточний елемент масиву (один октет)
    return (acc << 8) + parseInt(octet, 10);    //Зсуваємо накопичене на 8 біт вліво (множимо на 256) і додаємо новий октет, перетворений у число через parseInt
  }
  return octets.reduce(shiftAdd, 0);   // Запускаємо reduce над масивом октетів: shiftAdd — функція-правило, 0 — стартове значення накопичувача
}                                      // reduce сам пройде по масиву, сам викличе shiftAdd для кожного октету, сам оновить накопичувач і поверне фінальне число

console.log(ipToInt());
